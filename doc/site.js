/* slip0039 website: the split demo, using slip0039.js; plain JavaScript,
 * nothing is loaded from elsewhere */
"use strict";

(function () {

var SCHEMES = [
	{ gt: 1, groups: [[1, 1]], args: "1 1of1" },
	{ gt: 1, groups: [[2, 3]], args: "1 2of3" },
	{ gt: 1, groups: [[3, 5]], args: "1 3of5" },
	{ gt: 2, groups: [[2, 3], [3, 5], [1, 1]], args: "2 2of3 3of5 1of1" }
];

var HINTS = {
	numeric: "Any number of digits.",
	password: "Letters and digits, as generated by a password manager.",
	base16: "16 to 64 bytes in hexadecimal."
};

var EXAMPLES = {
	numeric: "042195",
	password: "k3V9pQ2mX7zR4tB8wN6y",
	base16: "bb54aac4b89dc868ba37d9cc21b2cece"
};

var $ = function (id) { return document.getElementById(id); };
var state = { codec: "numeric", scheme: 1, result: null, chosen: [], words: "" };
var run = 0;

function pressed(container, button) {
	Array.prototype.forEach.call(container.querySelectorAll("button"), function (b) {
		b.setAttribute("aria-pressed", b === button ? "true" : "false");
	});
}

/* quote for a POSIX shell */
function sq(s) {
	return "'" + s.replace(/'/g, "'\\''") + "'";
}

function codecArg(secret) {
	if (state.codec === "base16") return "";
	return " -c " + state.codec + "::" + secret.length;
}

function countOf(secret) {
	return state.codec === "base16" ? 0 : secret.length;
}

function renderShares(result) {
	var list = $("shares"), scheme = SCHEMES[state.scheme];
	list.textContent = "";
	result.shares.forEach(function (sh, i) {
		if (scheme.groups.length > 1 && sh.member === 0) {
			var g = scheme.groups[sh.group], li = document.createElement("li");
			li.className = "group-label";
			li.textContent = "Group " + (sh.group + 1) + ": " + g[0] +
				" of " + g[1] + " needed";
			list.appendChild(li);
		}
		var item = document.createElement("li"), b = document.createElement("button");
		b.type = "button";
		b.className = "share";
		b.setAttribute("aria-pressed", state.chosen.indexOf(i) >= 0 ? "true" : "false");
		var tag = document.createElement("span");
		tag.className = "tag";
		tag.textContent = scheme.groups.length > 1 ?
			(sh.group + 1) + "." + (sh.member + 1) : String(sh.member + 1);
		var words = document.createElement("span");
		words.className = "words";
		var w = sh.words.split(" ");
		w.forEach(function (word, k) {
			if (k) words.appendChild(document.createTextNode(" "));
			if (k < 4 || k >= w.length - 3) {
				var bb = document.createElement("b");
				bb.textContent = word;
				words.appendChild(bb);
			} else words.appendChild(document.createTextNode(word));
		});
		b.appendChild(tag);
		b.appendChild(words);
		b.addEventListener("click", function () {
			var at = state.chosen.indexOf(i);
			if (at >= 0) state.chosen.splice(at, 1);
			else state.chosen.push(i);
			b.setAttribute("aria-pressed", at >= 0 ? "false" : "true");
			recover();
		});
		item.appendChild(b);
		list.appendChild(item);
	});
}

/* the default choice: just enough shares, the first and last of a group */
function defaultChoice(result) {
	var scheme = SCHEMES[state.scheme], chosen = [];
	scheme.groups.forEach(function (g, gi) {
		if (gi >= scheme.gt) return;
		var idx = [];
		result.shares.forEach(function (sh, i) { if (sh.group === gi) idx.push(i); });
		var pick = idx.slice(0, g[0] - 1);
		pick.push(idx[idx.length - 1]);
		chosen = chosen.concat(pick);
	});
	return chosen;
}

async function recover() {
	var out = $("result"), result = state.result;
	if (!result) return;
	var chosen = state.chosen.map(function (i) { return result.shares[i]; });
	var mine = ++run;
	try {
		var r = await SLIP0039.recover(result, chosen, $("rpass").value);
		if (mine !== run) return;
		if (!r.ms) {
			out.textContent = chosen.length ? "Not enough shares selected yet." :
				"Select shares to recover from.";
			return;
		}
		var secret = $("secret").value.trim();
		var got = SLIP0039.decodeSecret(state.codec, r.ms, countOf(secret));
		var right = got === (state.codec === "base16" ? secret.toLowerCase() : secret);
		out.innerHTML = "";
		out.appendChild(document.createTextNode("Recovered from " + chosen.length +
			(chosen.length === 1 ? " share: " : " shares: ")));
		var s = document.createElement("samp");
		s.textContent = got;
		out.appendChild(s);
		out.appendChild(document.createElement("br"));
		var b = document.createElement("b");
		b.textContent = right ? "The secret you split." :
			"Not the secret you split, yet nothing in it shows that.";
		out.appendChild(b);
	} catch (e) {
		if (mine === run) out.textContent = e.message;
	}
}

async function split(again) {
	var err = $("err"), secretInput = $("secret");
	var secret = secretInput.value.trim(), seed = $("seed").value;
	var passphrase = $("passphrase").value, scheme = SCHEMES[state.scheme];
	err.textContent = "";
	secretInput.setAttribute("aria-invalid", "false");
	if (/[^\x20-\x7e]/.test(passphrase))
		return fail("The passphrase must consist of printable ASCII characters.");
	if (!seed.length) return fail("Give a seed, preferably 64 or more random characters.");
	var t0 = performance.now(), ms, result;
	try {
		ms = await SLIP0039.encodeSecret(state.codec, secret, seed);
		result = await SLIP0039.split({ passphrase: passphrase, seed: seed, ms: ms,
			e: 0, gt: scheme.gt, groups: scheme.groups });
	} catch (e) {
		secretInput.setAttribute("aria-invalid", "true");
		return fail(e.message);
	}
	var words = result.shares.map(function (s) { return s.words; }).join("\n");
	$("same").hidden = !(again && words === state.words);
	state.words = words;
	state.result = result;
	if (!again) state.chosen = defaultChoice(result);
	var ms_ = Math.round(performance.now() - t0);
	$("status").textContent = "";
	var st = document.createElement("span");
	$("status").appendChild(st);
	st.appendChild(document.createTextNode("Identifier "));
	var b1 = document.createElement("b"); b1.textContent = result.id; st.appendChild(b1);
	st.appendChild(document.createTextNode(", " + result.shares.length + " shares of " +
		(4 + Math.floor((8 * ms.length + 9) / 10) + 3) + " words, computed in "));
	var b2 = document.createElement("b"); b2.textContent = ms_ + " ms"; st.appendChild(b2);
	renderShares(result);
	$("cmd").textContent = "printf '%s\\n' " + sq(passphrase) + " " + sq(seed) + " " +
		sq(secret) + " |\n    slip0039" + codecArg(secret) + " split 0 " + scheme.args;
	if (seed.length < 64) err.textContent = "slip0039 warns about a seed shorter than 64 characters.";
	recover();

	function fail(msg) {
		err.textContent = msg;
		state.result = null;
		$("shares").textContent = "";
		$("result").textContent = "";
		$("status").textContent = "No shares.";
	}
}

var timer = null;
function later() {
	clearTimeout(timer);
	$("same").hidden = true;
	timer = setTimeout(function () { split(false); }, 250);
}

$("codec").addEventListener("click", function (ev) {
	var b = ev.target.closest("button");
	if (!b) return;
	pressed(this, b);
	state.codec = b.dataset.codec;
	$("secret").value = EXAMPLES[state.codec];
	$("secret-hint").textContent = HINTS[state.codec];
	split(false);
});

$("scheme").addEventListener("click", function (ev) {
	var b = ev.target.closest("button");
	if (!b) return;
	pressed(this, b);
	state.scheme = +b.dataset.scheme;
	split(false);
});

["passphrase", "seed", "secret"].forEach(function (id) {
	$(id).addEventListener("input", later);
});
$("rpass").addEventListener("input", recover);
$("again").addEventListener("click", function () { split(true); });
$("split").addEventListener("submit", function (ev) { ev.preventDefault(); });

if (!globalThis.crypto || !globalThis.crypto.subtle) {
	$("status").textContent = "This browser does not offer the Web Crypto API here, so the demo cannot run.";
} else split(false);

})();
