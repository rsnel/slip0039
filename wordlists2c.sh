fatal() {
	echo $1 >&2
	exit 1
}

if [ "$#" != "0" ]; then
	fatal "wrong number of arguments given"
fi

if ! command -v sha256sum >/dev/null && command -v shasum >/dev/null; then
	sha256sum() { shasum -a 256 "$@"; }
fi

INIT="void wordlists_init() {\n\tcodec_t *c;\n"
#DECL=""

# filename_prefix sha256 lines
format_wordlist() {
	if [ "$2" = "" ]; then
		FILENAME=wordlists/wordlist_$1.txt
		WORDLIST=wordlist_$1
	else
		FILENAME=wordlists/wordlist_$1_$2.txt
		WORDLIST=wordlist_$1_$2
	fi
	if [ ! -f "$FILENAME" ]; then
		fatal "file \"$FILENAME\" not found"
	fi

	if [ ! -r "$FILENAME" ]; then
		fatal "file \"$FILENAME\" is not readable"
	fi

	if [ "$3" != `sha256sum "$FILENAME" | cut -f 1 -d ' '` ]; then
		fatal "sha256sum of \"$FILENAME\" does not match"
	fi

	NUM=`wc -l $FILENAME | awk '{print $1}'`

	if [ "$NUM" != "$4" ]; then
		fatal "file $FILENAME has $NUM lines, when $4 lines were expected"
	fi

	# use LANG=C to get the bytecount of word lenght instead of character count
	MAX_WORD_LENGTH=`LANG=C awk -vmax=0 'length($0) > max {max = length($0)} END {print max}' < "$FILENAME"`
	MIN_WORD_LENGTH=`LANG=C awk -vmin=255 'length($0) < min {min = length($0)} END {print min}' < "$FILENAME"`
	echo
	echo wordlist_t $WORDLIST = {
	echo "\t.elt.key = \"$2\","
	echo "\t.family = \"$1\","
	echo "\t.max_word_length = $MAX_WORD_LENGTH,"
	echo "\t.min_word_length = $MIN_WORD_LENGTH,"
	echo "\t.words = (char *[]){"
	# escape backslashes and double quotes, they may occur in alphabets
	sed 's/[\\"]/\\&/g;s/^/\t\t"/;s/$/",/' < "$FILENAME"
	echo "\t}"
	echo "};"
	INIT="$INIT\tfixnum_multiplier16_init(&$WORDLIST.m, $4);\n"
#	if [ "${FAMILIES["$1"]}" = "" ]; then
#		DECL="${DECL}shashtbl_t wordlists_$1;\n"
#		INIT="$INIT\tshashtbl_init_simple(&wordlists_$1, 4, 1);\n"
#		FAMILIES[$1]="known"
#	fi
#	if [ "$2" != "" ]; then
	if [ "$REGISTER" = "1" ]; then
		INIT="$INIT\tif ((c = codec_find(\"$1\"))) shashtbl_add_elt(&c->wordlists,\n\t\t\t&$WORDLIST); else FATAL(\"codec $1 not found\");\n"
	fi
#	fi
}

REGISTER=1

# an alphabet is a wordlist that is used directly by one or more codecs,
# it is not registered as a selectable wordlist of a codec
format_alphabet() {
	REGISTER=0
	format_wordlist "$@"
	REGISTER=1
}

